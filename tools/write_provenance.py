"""Write docs/PROVENANCE.md (the provenance table required by the content rules)
and docs/COUNTS.md (entry and link counts per work) from the database.

    python3 tools/write_provenance.py
"""

import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from library.db import DB_PATH  # noqa: E402


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def main():
    con = sqlite3.connect(DB_PATH)
    works = con.execute("""SELECT w.id, w.code, w.title, rt.name, w.original_date, w.edition, w.source_name,
                                  w.source_url, w.license_status, w.license_evidence, w.attribution_required,
                                  w.attribution_text, w.coverage, w.known_issues, w.date_ingested,
                                  w.launch_status, w.launch_note
                           FROM works w JOIN reference_types rt ON rt.id = w.reference_type_id
                           ORDER BY rt.id, w.code""").fetchall()
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    out = ["# Provenance of every work in the library", "",
           "Generated from the database by `tools/write_provenance.py`. Every work is public domain; "
           "none requires attribution. Raw files are not kept in the repository; the URLs below are where "
           "the ingest scripts download them from, and the SHA-256 checksums identify the exact files used.", ""]
    for (wid, code, title, rtype, odate, edition, sname, surl, lic, ev, attr, attr_text, cov, issues,
         ingested, launch, launch_note) in works:
        authors = ", ".join(r[0] for r in con.execute(
            "SELECT a.name FROM work_authors wa JOIN authors a ON a.id = wa.author_id WHERE wa.work_id = ? "
            "ORDER BY wa.position", (wid,)))
        out += [f"## {title} (`{code}`)", "",
                "| Field | Value |", "|---|---|",
                f"| Author(s) | {cell(authors)} |",
                f"| Reference type | {rtype} |",
                f"| First published | {cell(odate)} |",
                f"| Edition used | {cell(edition)} |",
                f"| Source | {cell(sname)} - {cell(surl)} |",
                f"| License status | **{cell(lic)}** |",
                f"| License evidence | {cell(ev)} |",
                f"| Attribution required | {'Yes: ' + cell(attr_text) if attr else 'No'} |",
                f"| Coverage | {cell(cov)} |",
                f"| Known issues | {cell(issues) or 'None noted'} |",
                f"| Launch status | {('**' + cell(launch).upper() + '** - ' + cell(launch_note)) if launch else 'OK to launch'} |",
                f"| Ingested | {ingested} |", "",
                "| Raw file | Downloaded from | Retrieved | Bytes | SHA-256 |", "|---|---|---|---|---|"]
        for fn, url, when, size, sha in con.execute(
                "SELECT file_name, source_url, retrieved_at, bytes, sha256 FROM provenance WHERE work_id = ?", (wid,)):
            out.append(f"| {fn} | {url} | {when} | {size:,} | `{sha[:16]}...` |")
        out.append("")
    open(os.path.join(ROOT, "docs", "PROVENANCE.md"), "w").write("\n".join(out))

    rows = con.execute("""
        SELECT w.code, w.short_title, rt.name,
               (SELECT COUNT(*) FROM bible_text b WHERE b.work_id = w.id),
               (SELECT COUNT(*) FROM entries e WHERE e.work_id = w.id),
               (SELECT COUNT(*) FROM entry_scripture es JOIN entries e ON e.id = es.entry_id WHERE e.work_id = w.id),
               (SELECT COUNT(*) FROM entry_subjects es JOIN entries e ON e.id = es.entry_id
                 WHERE e.work_id = w.id AND es.method = 'structural'),
               (SELECT COUNT(*) FROM entry_subjects es JOIN entries e ON e.id = es.entry_id
                 WHERE e.work_id = w.id AND es.method = 'ai'),
               (SELECT COUNT(*) FROM entry_subjects es JOIN entries e ON e.id = es.entry_id
                 WHERE e.work_id = w.id AND es.review_status = 'needs_review'),
               (SELECT COUNT(*) FROM cross_references c WHERE c.source_work_id = w.id),
               (SELECT COUNT(*) FROM subject_scripture s WHERE s.source_work_id = w.id),
               (SELECT COUNT(*) FROM verse_words v WHERE v.work_id = w.id),
               (SELECT SUM(word_count) FROM entries e WHERE e.work_id = w.id)
        FROM works w JOIN reference_types rt ON rt.id = w.reference_type_id ORDER BY rt.id, w.code""").fetchall()
    out = ["# Entry and link counts per work", "", "Generated by `tools/write_provenance.py`.", "",
           "| Work | Type | Verses | Entries | Words | Scripture links | Subject links (structural) | "
           "Subject links (machine) | Awaiting review | Other links |", "|---|---|---|---|---|---|---|---|---|---|"]
    for code, short, rtype, verses, ents, refs, st, ai, rev, xref, subj, words, nwords in rows:
        other = []
        if xref:
            other.append(f"{xref:,} verse cross-references")
        if subj:
            other.append(f"{subj:,} subject-verse links")
        if words:
            other.append(f"{words:,} word-Strong's links")
        out.append(f"| {short} (`{code}`) | {rtype} | {verses or ''} | {ents:,} | {nwords or 0:,} | {refs:,} | "
                   f"{st:,} | {ai:,} | {rev:,} | {'; '.join(other)} |")
    tot = con.execute("SELECT (SELECT COUNT(*) FROM subjects WHERE level='topic'), "
                      "(SELECT COUNT(*) FROM subjects WHERE level='subtopic'), "
                      "(SELECT COUNT(*) FROM subjects WHERE level='category'), "
                      "(SELECT COUNT(*) FROM review_queue), (SELECT COUNT(*) FROM spot_checks)").fetchone()
    out += ["", f"Subjects: {tot[0]:,} Nave's topics, {tot[1]:,} sub-headings, {tot[2]} top-level categories "
                f"(waiting for Dave). Review list: {tot[3]:,} links. Spot checks recorded: {tot[4]}.", "",
            "| Related-subject link type | Count |", "|---|---|"]
    for rel, n in con.execute("SELECT relation, COUNT(*) FROM subject_relations GROUP BY relation"):
        out.append(f"| {rel} | {n:,} |")
    open(os.path.join(ROOT, "docs", "COUNTS.md"), "w").write("\n".join(out) + "\n")
    print("wrote docs/PROVENANCE.md and docs/COUNTS.md")


if __name__ == "__main__":
    main()
